"""`requirements/ci-py310.txt`: the 3.10 test run's lock, held to CI's (#242).

80's ruling (3961 on #242): the slot-B 3.10 targeted run installs a hashed
lock compiled with `--python-version 3.10` from the same inputs as
`requirements/ci.txt`, so a merge-blocking run is reproducible and an
upstream release can't turn it red under an unrelated PR (3970: an unpinned
resolve took litellm 1.104.0 and failed three tests no PR had touched).

So it must differ from `ci.txt` only where 3.10 forces it: the run then
differs from CI in the interpreter and those pins, as 80 put it (3982). It
is compiled with `ci.txt`'s pins as its starting point, so uv keeps every
pin 3.10 can meet. These hold that, and that `ci_in_docker` reproduces it
from its header with the other locks.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CI = ROOT / "requirements" / "ci.txt"
PY310 = ROOT / "requirements" / "ci-py310.txt"

#: Pins that differ on 3.10, each with why: `ci.txt`'s version stays, for
#: 3.11 and up, beside uv's pick for `python_full_version < '3.11'`. The
#: reasons are 1d's measurement (3957) and 9b's (3979) on #242.
SPLIT_FOR_310 = {
    "rpds-py": "2026.6.3 has no 3.10 distribution; uv picks 0.30.0 there",
    "stevedore": "5.9.1 requires Python >=3.11; uv picks 5.8.0 there",
}
#: Backports the 3.10 standard library lacks, pulled in only there (the
#: lock's own `# via` lines).
ONLY_ON_310 = {
    "async-timeout": "asyncio.timeout arrived in 3.11; via aiohttp",
    "exceptiongroup": "ExceptionGroup arrived in 3.11; via anyio and pytest",
}

_PIN = re.compile(r"^([A-Za-z0-9_.\-]+)==([^\s;\\]+)", re.MULTILINE)


def _pins(path: Path) -> dict[str, set[str]]:
    found: dict[str, set[str]] = {}
    for name, version in _PIN.findall(path.read_text(encoding="utf-8")):
        found.setdefault(name.lower(), set()).add(version)
    return found


def _header(path: Path) -> str:
    return path.read_text(encoding="utf-8").splitlines()[1].removeprefix("#    ")


def test_it_is_compiled_from_ci_txts_inputs_for_310():
    ci, py310 = _header(CI), _header(PY310)
    assert "--python-version 3.12" in ci and "-o requirements/ci.txt" in ci
    assert py310 == ci.replace("--python-version 3.12", "--python-version 3.10").replace(
        "-o requirements/ci.txt", "-o requirements/ci-py310.txt"
    )


def test_every_ci_pin_is_kept_except_where_310_forces_otherwise():
    ci, py310 = _pins(CI), _pins(PY310)
    missing = sorted(name for name in ci if name not in py310)
    assert not missing, f"in ci.txt but not the 3.10 lock: {missing}"
    lost = sorted(name for name, versions in ci.items() if not versions <= py310[name])
    assert not lost, f"the 3.10 lock doesn't keep ci.txt's version of: {lost}"
    extra = {name for name, versions in py310.items() if versions - ci.get(name, set())}
    assert extra == set(SPLIT_FOR_310) | set(ONLY_ON_310), (
        "a pin differs from ci.txt without a stated reason; recompile ci-py310.txt "
        "starting from ci.txt's pins (copy ci.txt over it, then run its header)"
    )


def test_the_packages_whose_drift_turned_the_310_run_red_are_ci_txts():
    """3970: an unpinned resolve took litellm 1.104.0 and three tests failed."""
    ci, py310 = _pins(CI), _pins(PY310)
    for name in ("litellm", "pytest", "pytest-xdist"):
        assert py310[name] == ci[name], name


def test_ci_in_docker_reproduces_every_uv_lock_from_its_header():
    """The other side of the check is the files on disk: every lock uv wrote
    under requirements/ is in the loop, so a new one can't be left out."""
    script = (ROOT / "scripts" / "ci_in_docker.py").read_text(encoding="utf-8")
    (loop,) = re.findall(r"for lock in ([^;]+); do", script)
    looped = set(loop.split())
    on_disk = {
        path.relative_to(ROOT).as_posix()
        for path in (ROOT / "requirements").rglob("*.txt")
        if path.read_text(encoding="utf-8").startswith("# This file was autogenerated by uv")
    }
    assert "requirements/ci-py310.txt" in on_disk, "premise: the lock is on disk"
    assert on_disk <= looped, f"not reproduced by ci_in_docker: {sorted(on_disk - looped)}"
