JOB = "brew-macos"


@pytest.mark.github_config
@pytest.mark.parametrize("where, repository, event, ref, runs", CONTEXTS)
def test_the_job_runs_only_for_a_candidate_on_the_private_test_repo(
    where, repository, event, ref, runs
):
    guard = _jobs()[JOB]["if"]
    assert _holds(guard, repository=repository, event_name=event, ref=ref) is runs, where


@pytest.mark.github_config
def test_the_job_is_on_a_mac_and_a_candidate_must_pass_it():
    job = _jobs()[JOB]
    assert job["runs-on"] == "macos-latest"
    assert any(rule.fullmatch(job["name"]) for rule in pp.CI_REQUIRED), job["name"]
    assert sum(bool(rule.fullmatch(job["name"])) for rule in pp.CI_REQUIRED) == 1


@pytest.mark.github_config
def test_the_job_builds_the_formula_from_the_candidate_with_the_lock_script():
    runs = _runs(JOB)
    make = runs["Make the candidate's formula"]
    archive = "git archive --format=tar.gz --prefix=policyforge/"
    out = '-o "$RUNNER_TEMP/policyforge.tar.gz"'
    assert f"{archive} {out} HEAD" in make
    assert "python scripts/formula_resources.py --tap" in make
    assert "brew update-python-resources" not in "".join(runs.values())
    assert (ROOT / "scripts" / "formula_resources.py").is_file()


@pytest.mark.github_config
def test_the_job_installs_from_source_then_runs_brew_test_and_the_cli_checks():
    runs = _runs(JOB)
    install = runs["brew install --build-from-source, then brew test"]
    order = [
        "brew install --build-from-source local/candidate/policyforge",
        "brew test local/candidate/policyforge",
    ]
    assert [install.index(step) for step in order] == sorted(install.index(s) for s in order)
    assert "brew --version" in runs["Which Homebrew"]
    tool = runs["The installed tool"]
    assert "version_step" in tool and "policyforge init" in tool
    assert "frameworks=$(policyforge frameworks)" in tool
    assert 'grep -q nist-800-53-r5 <<< "$frameworks"' in tool
    assert "|" not in tool.replace("||", ""), "a pipe takes its status from its right side"


@pytest.mark.github_config
def test_every_step_that_chains_commands_uses_bash_so_a_failure_stops_it():
    for step in _jobs()[JOB]["steps"]:
        if "run" in step:
            assert step.get("shell") == "bash", step.get("name")
